//! A 5x7 bitmap font for diagnostics: enough to put the GL renderer, the frame
//! rate and key codes on screen before the shell has a real text engine.
//! Lower case is drawn as upper case; anything unknown is drawn as `?`.

pub const GLYPH_W: u32 = 5;
pub const GLYPH_H: u32 = 7;
/// Horizontal distance from one character to the next, in font pixels.
pub const ADVANCE: u32 = GLYPH_W + 1;

/// Rows top to bottom; bit 4 is the leftmost pixel.
type Glyph = [u8; GLYPH_H as usize];

const UNKNOWN: Glyph = [0x0E, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04];

fn glyph(c: char) -> Glyph {
    match c.to_ascii_uppercase() {
        ' ' => [0; 7],
        '0' => [0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E],
        '1' => [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E],
        '2' => [0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F],
        '3' => [0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E],
        '4' => [0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02],
        '5' => [0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E],
        '6' => [0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E],
        '7' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
        '8' => [0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E],
        '9' => [0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C],
        'A' => [0x0E, 0x11, 0x11, 0x11, 0x1F, 0x11, 0x11],
        'B' => [0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E],
        'C' => [0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E],
        'D' => [0x1C, 0x12, 0x11, 0x11, 0x11, 0x12, 0x1C],
        'E' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F],
        'F' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10],
        'G' => [0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F],
        'H' => [0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'I' => [0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E],
        'J' => [0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C],
        'K' => [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11],
        'L' => [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F],
        'M' => [0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11],
        'N' => [0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11],
        'O' => [0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'P' => [0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10],
        'Q' => [0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D],
        'R' => [0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11],
        'S' => [0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E],
        'T' => [0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04],
        'U' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'V' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04],
        'W' => [0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A],
        'X' => [0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11],
        'Y' => [0x11, 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04],
        'Z' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F],
        '.' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C],
        ',' => [0x00, 0x00, 0x00, 0x00, 0x0C, 0x04, 0x08],
        '-' => [0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00],
        '_' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1F],
        ':' => [0x00, 0x0C, 0x0C, 0x00, 0x0C, 0x0C, 0x00],
        '/' => [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x00],
        '(' => [0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02],
        ')' => [0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08],
        '[' => [0x0E, 0x08, 0x08, 0x08, 0x08, 0x08, 0x0E],
        ']' => [0x0E, 0x02, 0x02, 0x02, 0x02, 0x02, 0x0E],
        '%' => [0x18, 0x19, 0x02, 0x04, 0x08, 0x13, 0x03],
        '+' => [0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00],
        '=' => [0x00, 0x00, 0x1F, 0x00, 0x1F, 0x00, 0x00],
        '#' => [0x0A, 0x0A, 0x1F, 0x0A, 0x1F, 0x0A, 0x0A],
        '*' => [0x00, 0x04, 0x15, 0x0E, 0x15, 0x04, 0x00],
        '\'' => [0x0C, 0x04, 0x08, 0x00, 0x00, 0x00, 0x00],
        _ => UNKNOWN,
    }
}

/// Calls `pixel(x, y)` for every lit pixel of `text`, in font pixels from the
/// string's top-left corner.
pub fn for_each_pixel(text: &str, mut pixel: impl FnMut(u32, u32)) {
    for (i, c) in text.chars().enumerate() {
        let origin = i as u32 * ADVANCE;
        for (y, row) in glyph(c).iter().enumerate() {
            for x in 0..GLYPH_W {
                if row & (0x10 >> x) != 0 {
                    pixel(origin + x, y as u32);
                }
            }
        }
    }
}

/// Width of `text` in font pixels, without trailing spacing.
pub fn width(text: &str) -> u32 {
    match text.chars().count() as u32 {
        0 => 0,
        n => n * ADVANCE - 1,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const SUPPORTED: &str = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ.,-_:/()[]%+=#*'";

    #[test]
    fn every_glyph_fits_five_columns() {
        for c in SUPPORTED.chars() {
            for row in glyph(c) {
                assert!(row < 0x20, "{c:?} has a row wider than 5 pixels");
            }
        }
    }

    #[test]
    fn supported_glyphs_are_distinct_and_known() {
        let glyphs: Vec<Glyph> = SUPPORTED.chars().map(glyph).collect();
        for (i, a) in glyphs.iter().enumerate() {
            assert_ne!(
                *a,
                UNKNOWN,
                "{:?} falls back to ?",
                SUPPORTED.chars().nth(i)
            );
            for b in &glyphs[i + 1..] {
                assert_ne!(a, b, "two glyphs share a bitmap");
            }
        }
    }

    #[test]
    fn lower_case_draws_as_upper_case_and_unknown_as_question_mark() {
        assert_eq!(glyph('m'), glyph('M'));
        assert_eq!(glyph('~'), UNKNOWN);
        assert_eq!(glyph('?'), UNKNOWN);
    }

    #[test]
    fn space_lights_nothing_and_width_ignores_trailing_gap() {
        let mut lit = 0;
        for_each_pixel("   ", |_, _| lit += 1);
        assert_eq!(lit, 0);
        assert_eq!(width(""), 0);
        assert_eq!(width("A"), GLYPH_W);
        assert_eq!(width("AB"), ADVANCE + GLYPH_W);
    }

    #[test]
    fn second_character_starts_one_advance_along() {
        let mut xs = Vec::new();
        for_each_pixel(" I", |x, y| {
            if y == 0 {
                xs.push(x);
            }
        });
        assert_eq!(xs, vec![ADVANCE + 1, ADVANCE + 2, ADVANCE + 3]);
    }
}
